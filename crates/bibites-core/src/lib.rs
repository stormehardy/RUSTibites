/// NEAT neural network: topology, activations, execution. Owner: brain-dev.
pub mod brain;
/// Bibite genes, mutation and genome-level data. Owner: brain-dev.
pub mod genome;
/// The words species are named after, the game's own list (generated by `tools/extract_latin_names.py`).
mod latin_names;
/// Species assignment, lineage tracking and speciation stats. Owner: brain-dev.
pub mod species;
/// The multi-resolution history of a species (the lineage tree reads it). Owner: brain-dev.
pub mod species_log;
/// The framing of a save's `data.bin` (the species block). Owner: brain-dev.
pub mod data_bin;

/// Bibite body state, size/mass, damage and lifecycle. Owner: body-dev.
pub mod body;
/// Organs: mouth, stomach, propulsion, fat, armour, egg, growth, clock. Owner: body-dev.
pub mod organs;
/// Custom 2D physics: broadphase, narrowphase, contacts, resolution. Owner: body-dev.
pub mod physics;

/// Plant/meat pellets, matter, decay and materials. Owner: world-dev.
pub mod pellet;
pub mod pellet_sleep;
/// Pheromone emission, decay and sensing helpers. Owner: world-dev.
pub mod pheromone;
/// Chooses, by measuring the world's own ticks, whether a tick runs inline or on the worker pool.
pub mod pool_tuner;
/// Vision (field of view) and pheromone sensing. Owner: world-dev.
pub mod senses;
/// Simulation orchestration: system scheduling, stats, run configuration. Owner: world-dev.
pub mod sim;
/// Scenario world tools: radiation/pheromone/effect towers, colour killers. Owner: world-dev.
pub mod tools;
/// World container and central tick driver. Owner: world-dev.
pub mod world;
/// Zones, plant biomass and spawning. Owner: world-dev.
pub mod zone;
/// The multi-resolution history of a zone (the species Position tab reads it). Owner: world-dev.
pub mod zone_log;

/// Simulation settings: typed model and exact defaults. Owner: fmt-dev.
pub mod settings;

