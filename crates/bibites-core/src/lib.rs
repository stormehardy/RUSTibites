//! # bibites-core
//!
//! Headless, deterministic simulation core for **RUSTibites**, an open-source
//! Rust reimplementation of [The Bibites](https://thebibites.com/).
//!
//! The crate is deliberately dependency-free so that the simulation is easy to
//! audit, portable, and reproducible bit-for-bit on every platform. All maths
//! is `f32` (matching the original Unity game), all randomness comes from
//! explicitly seeded [`Rng`] streams, and the hot loop is designed for
//! structure-of-arrays storage with a central fixed-timestep driver.
//!
//! ## Module ownership
//!
//! The modules below are split into disjoint areas so that several people can
//! work in parallel. Each module has a single owner; do not edit another
//! owner's module without coordinating through the Lead.
//!
//! | Area | Modules | Owner |
//! |------|---------|-------|
//! | Foundation | [`math`], [`rng`], [`arena`], [`ids`], [`error`], [`clock`] | Lead |
//! | Brain & genetics | [`genome`], [`brain`], [`species`] | brain-dev |
//! | Body & organs | [`body`], [`organs`], [`physics`] | body-dev |
//! | World & ecology | [`world`], [`zone`], [`pellet`], [`pheromone`], [`senses`], [`tools`], [`sim`] | world-dev |
//! | Settings & formats | [`settings`] | fmt-dev |
//!
//! ## Determinism
//!
//! * One authoritative tick sequence: the world advances in fixed steps of
//!   `1 / sim_tps` seconds (default 30 TPS, as in the original game; a scenario/save may override it).
//! * All random decisions use [`Rng`]; no `rand`-style global state and no
//!   thread-local randomness is permitted in simulation code.
//! * Parallel execution is allowed only where the work for each entity is
//!   independent and consumes its own derived RNG stream, so enabling threads
//!   must not change results.
//!
//! ## Fidelity policy
//!
//! Equations, constants, defaults and update order follow the decompiled
//! original (`Z:\RUSTibites\Here`) as documented in `docs/spec/`. Physics is
//! the one intentional divergence: a purpose-built solver replaces Unity's
//! Box2D for speed, aiming for behaviourally equivalent results rather than
//! contact-identical trajectories.

