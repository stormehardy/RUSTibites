"""Extracts the settings-UI metadata (labels, helper text, units, precision, SI, factor, ...)
from the decompiled game source into crates/bibites-view/src/setting_ui_data.rs.

Usage: python tools/extract_setting_ui.py [Here] [out.rs]

Sources: Here/SettingScripts/ScenarioSettings.cs, ScenarioIndependentSettings.cs.
Each `public (Float|Int|Bool)Setting field = new ...Setting { Name = ..., ... };`
becomes one row of `SETTING_UI` (the C# field name is the core's setting key).
Run again after the game is updated; `Here/` is not part of the repository.
"""
import re
import sys
from pathlib import Path

here = Path(sys.argv[1] if len(sys.argv) > 1 else 'Here')
out_path = Path(sys.argv[2] if len(sys.argv) > 2 else 'crates/bibites-view/src/setting_ui_data.rs')

SOURCES = [
    ('Scenario', here / 'SettingScripts' / 'ScenarioSettings.cs'),
    ('Independent', here / 'SettingScripts' / 'ScenarioIndependentSettings.cs'),
]

DECL = re.compile(r'^\tpublic (Float|Int|Bool)Setting (\w+) = new \1Setting\s*$', re.M)


def unescape(raw: str) -> str:
    out = []
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == '\\' and i + 1 < len(raw):
            n = raw[i + 1]
            if n == 'n':
                out.append('\n')
            elif n == 'r':
                out.append('\r')
            elif n == 't':
                out.append('\t')
            elif n in '"\\\'':
                out.append(n)
            elif n == 'u' and i + 5 < len(raw) + 0:
                out.append(chr(int(raw[i + 2:i + 6], 16)))
                i += 4
            else:
                out.append(n)
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def rust_str(text: str) -> str:
    parts = []
    for ch in text:
        if ch == '\\':
            parts.append('\\\\')
        elif ch == '"':
            parts.append('\\"')
        elif ch == '\n':
            parts.append('\\n')
        elif ch == '\r':
            parts.append('\\r')
        elif ch == '\t':
            parts.append('\\t')
        elif ord(ch) < 0x20 or ord(ch) > 0x7E:
            parts.append('\\u{%x}' % ord(ch))
        else:
            parts.append(ch)
    return '"' + ''.join(parts) + '"'


def num(text: str) -> float:
    text = text.strip().rstrip('fF')
    return float(text)


def parse_block(block: str) -> dict:
    fields = {}
    # single-line `Key = value,` pairs; strings may contain commas and escaped quotes
    for m in re.finditer(r'^\t\t(\w+) = ("(?:[^"\\]|\\.)*"|[^,\n]+),?\s*$', block, re.M):
        key, value = m.group(1), m.group(2).strip()
        if value.startswith('"'):
            fields[key] = unescape(value[1:-1])
        elif value in ('true', 'false'):
            fields[key] = value == 'true'
        else:
            try:
                fields[key] = num(value)
            except ValueError:
                fields[key] = value  # enum / expression
    fields['_has_landmarks'] = 'landmarks' in block
    return fields


rows = []
for scope, path in SOURCES:
    text = path.read_text(encoding='utf-8-sig')
    for m in DECL.finditer(text):
        kind, field = m.group(1), m.group(2)
        start = text.index('{', m.end())
        end = text.index('\n\t};', start)
        fields = parse_block(text[start:end])
        rows.append((scope, kind, field, fields))

lines = [
    '//! Generated by `tools/extract_setting_ui.py` from the decompiled game source: the settings',
    '//! panel metadata (`Name`, `HelperText`, units, precision, SI, factor, ...) of every',
    '//! `ScenarioSettings` / `ScenarioIndependentSettings` entry. Do not edit by hand.',
    '',
    '#![allow(dead_code)] // tooltips (`helper`, `wiki`) are not wired yet',
    '',
    '/// Which core settings struct a row belongs to.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum SettingScope {',
    '    /// `ScenarioSettings` (`SimSettings::scenario`).',
    '    Scenario,',
    '    /// `ScenarioIndependentSettings` (`SimSettings::independents`).',
    '    Independent,',
    '}',
    '',
    '/// Value kind of a setting.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum SettingUiKind {',
    '    /// `FloatSetting`.',
    '    Float,',
    '    /// `IntSetting`.',
    '    Int,',
    '    /// `BoolSetting`.',
    '    Bool,',
    '}',
    '',
    '/// Display metadata of one setting (`NumericSetting` fields).',
    '#[derive(Clone, Copy, Debug)]',
    'pub struct SettingUi {',
    '    /// Core settings struct.',
    '    pub scope: SettingScope,',
    '    /// C# field name = core key.',
    '    pub field: &\'static str,',
    '    /// Value kind.',
    '    pub kind: SettingUiKind,',
    '    /// `Name` (row label).',
    '    pub name: &\'static str,',
    '    /// `HelperText` (tooltip).',
    '    pub helper: &\'static str,',
    '    /// `WikiLink` (empty when none).',
    '    pub wiki: &\'static str,',
    '    /// `DefaultValue`.',
    '    pub default: f32,',
    '    /// `minValue`.',
    '    pub min: f32,',
    '    /// `maxValue`.',
    '    pub max: f32,',
    '    /// `precision`.',
    '    pub precision: i32,',
    '    /// `units`.',
    '    pub units: &\'static str,',
    '    /// `prefix`.',
    '    pub prefix: &\'static str,',
    '    /// `factor`.',
    '    pub factor: f32,',
    '    /// `SI`.',
    '    pub si: bool,',
    '    /// `alwaysShowSign`.',
    '    pub always_show_sign: bool,',
    '    /// `canGoOutOfBounds`.',
    '    pub out_of_bounds: bool,',
    '}',
    '',
    '/// Every extracted setting.',
    'pub const SETTING_UI: &[SettingUi] = &[',
]


def f(value, default=0.0):
    value = default if value is None else value
    if isinstance(value, str):
        return '0.0'
    text = repr(float(value))
    return text


for scope, kind, field, fields in rows:
    name = fields.get('Name', field)
    entry = [
        '    SettingUi {',
        f'        scope: SettingScope::{scope},',
        f'        field: {rust_str(field)},',
        f'        kind: SettingUiKind::{kind},',
        f'        name: {rust_str(str(name))},',
        f'        helper: {rust_str(str(fields.get("HelperText", "")))},',
        f'        wiki: {rust_str(str(fields.get("WikiLink", "")))},',
        f'        default: {f(fields.get("DefaultValue"), 1.0 if fields.get("DefaultValue") is True else 0.0) if not isinstance(fields.get("DefaultValue"), bool) else ("1.0" if fields.get("DefaultValue") else "0.0")},',
        f'        min: {f(fields.get("minValue"))},',
        f'        max: {f(fields.get("maxValue"))},',
        f'        precision: {int(fields.get("precision", 0))},',
        f'        units: {rust_str(str(fields.get("units", "")))},',
        f'        prefix: {rust_str(str(fields.get("prefix", "")))},',
        f'        factor: {f(fields.get("factor"), 1.0)},',
        f'        si: {"true" if fields.get("SI", True) is not False else "false"},',
        f'        always_show_sign: {"true" if fields.get("alwaysShowSign", False) is True else "false"},',
        f'        out_of_bounds: {"true" if fields.get("canGoOutOfBounds", True) is not False else "false"},',
        '    },',
    ]
    lines.extend(entry)
lines.append('];')
lines.append('')
lines.append('/// Metadata of the setting with this core key.')
lines.append('#[must_use]')
lines.append('pub fn setting_ui(scope: SettingScope, field: &str) -> Option<&\'static SettingUi> {')
lines.append('    SETTING_UI')
lines.append('        .iter()')
lines.append('        .find(|row| row.scope == scope && row.field == field)')
lines.append('}')
lines.append('')
out_path.write_text('\n'.join(lines), encoding='utf-8')
print(len(rows), 'settings ->', out_path)
