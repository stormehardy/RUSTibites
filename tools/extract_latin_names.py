"""Extracts the words the game names species after into crates/bibites-core/src/latin_names.rs.

Usage: python tools/extract_latin_names.py [<game data dir>] [out.rs]

The game fills `SpeciesNameGenerator.latinNames` in `PatronsImporter.LoadPatronsInfo`
(Here/OneUseScripts/PatronsImporter.cs): the four entries written into the source (Leo, Borgpol, Aentek, MayZ),
then one entry for every row of the TextAsset `Resources/Patrons/patreon_supporters` (a CSV `name,pledge_amount,latinized`, found in
`resources.assets`), the whole list ordered by descending pledge (LINQ's `OrderByDescending` is stable, so equal pledges keep the
order they were added in), and `latinNames` is the `latinized` column of that list. Species are named from it by
`WeightedRandomPatron` (`1 - U^weight` of the list's length, weight 4 for a genus and 1.5 for an epithet: near 1 for most draws, so
the words at the END of the list, the smallest pledges, are the common ones).

Only the `latinized` column is written, in the game's order: the patrons' names and pledges are not copied. The words are kept exactly
as the game has them (some end in a space, some have letters like `ö`: the game uses them that way). A row is read the way the C#
reads it (a name with commas gets its extra columns merged, the quotes and spaces of the name and of the last two columns are
removed for such rows, a row missing a field is skipped). Needs UnityPy (`pip install UnityPy`).
Run again after the game is updated (the supporters' list grows).
"""
import glob
import os
import sys
from pathlib import Path

import UnityPy

data_dir = sys.argv[1] if len(sys.argv) > 1 else 'C:/Users/Storme/TheBibites/The Bibites_Data'
out_path = Path(sys.argv[2] if len(sys.argv) > 2 else 'crates/bibites-core/src/latin_names.rs')

# `PatronsImporter.patreonHistoryInfos` as written in the source: (name, total pledge, latinized).
BUILT_IN = [
    ('Léo, The Creator', 2**31 - 1, 'leo'),
    ('Borgpol', 100000, 'borgpolisi'),
    ('Aentek', 100000, 'aentekus'),
    ('MayZ', 100000, 'mayzi'),
]


def read_asset(directory: str) -> str:
    for path in sorted(glob.glob(os.path.join(directory, '*.assets'))):
        env = UnityPy.load(path)
        for obj in env.objects:
            if obj.type.name != 'TextAsset':
                continue
            data = obj.read()
            if getattr(data, 'm_Name', '') == 'patreon_supporters':
                script = data.m_Script
                return script if isinstance(script, str) else bytes(script).decode('utf-8')
    raise SystemExit(f'no TextAsset "patreon_supporters" in {directory}')


def parse(text: str) -> list[tuple[str, int, str]]:
    """`PatronsImporter.LoadPatronsInfo`, line by line."""
    entries = list(BUILT_IN)
    lines = text.replace('\r', '').split('\n')
    for line in lines[1:]:
        array = line.split(',')
        if len(array) > 3:
            first = array[0]
            for j in range(1, len(array) - 2):
                first += ',' + array[j]
            first = first.replace('"', '').replace(' ', '')
            array = [first, array[-2].replace(' ', ''), array[-1].replace(' ', '')]
        # `!IsNullOrEmpty(array[0]) && !IsNullOrEmpty(array[1]) && !IsNullOrEmpty(array[2])`: C# stops at the first empty field (a row
        # with fewer fields than that would throw there; indexing the same way makes this fail on such a row too).
        if array[0] and array[1] and array[2]:
            entries.append((array[0], int(array[1]), array[2]))
    # `OrderByDescending`: stable, which Python's sort is too.
    entries.sort(key=lambda entry: entry[1], reverse=True)
    return entries


def rust_str(text: str) -> str:
    parts = []
    for ch in text:
        if ch == '\\':
            parts.append('\\\\')
        elif ch == '"':
            parts.append('\\"')
        elif ord(ch) < 0x20:
            parts.append('\\u{%x}' % ord(ch))
        else:
            parts.append(ch)
    return '"' + ''.join(parts) + '"'


entries = parse(read_asset(data_dir))
words = [entry[2] for entry in entries]
lines = [
    '//! Generated by `tools/extract_latin_names.py` from the game\'s `Resources/Patrons/patreon_supporters` asset: the words species are',
    '//! named after (`SpeciesNameGenerator.latinNames`), in the order the game has them. Do not edit by hand.',
    '',
    '/// The game\'s `latinNames`: the four entries `PatronsImporter` writes into the source and the `latinized` column of the supporters\'',
    '/// list, ordered by descending pledge. The words are as the game has them, a trailing space and an `ö` included.',
    '#[rustfmt::skip]',
    'pub const LATIN_NAMES: &[&str] = &[',
]
lines.extend(f'    {rust_str(word)},' for word in words)
lines.append('];')
lines.append('')
out_path.parent.mkdir(parents=True, exist_ok=True)
out_path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
distinct = len(set(words))
odd = [word for word in words if not (word.isascii() and word.isalpha() and word.islower())]
print(f'{len(words)} words ({distinct} distinct) -> {out_path}')
print('first:', ', '.join(words[:6]))
print(f'{len(odd)} words are not plain lower-case ASCII letters, e.g.', ', '.join(repr(word) for word in odd[:6]))
