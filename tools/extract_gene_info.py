"""Extracts the 35 gene settings (name, help text, range and number format) in the order of
`BibiteEditorSettings.geneSettings` from the decompiled game source into
crates/bibites-view/src/gene_info_data.rs.

Usage: python tools/extract_gene_info.py [Here] [out.rs]

The species panel's Genes tab lists the genes in that order (`SpeciesGenesPanel.InitPanel`) with
`GeneSetting.Name`, its help text as the tooltip and `maxValue` for the contribution to speciation
(`GeneLineInfo.SetGene`). The Gene Analysis page's x axis and bar tooltips write the values with the setting's
`FloatSetting.formatting` (precision, prefix, units, factor, always show sign, SI; the defaults are those of
`NumericSetting`: precision 0, no prefix or units, factor 1, no sign, SI on). Run again after the game is updated; `Here/` is not part of the repository.
"""
import re
import sys
from pathlib import Path

here = Path(sys.argv[1] if len(sys.argv) > 1 else 'Here')
out_path = Path(sys.argv[2] if len(sys.argv) > 2 else 'crates/bibites-view/src/gene_info_data.rs')

source = (here / 'SettingScripts' / 'BibiteEditorSettings.cs').read_text(encoding='utf-8').replace('\r\n', '\n')

STRING = r'"((?:[^"\\]|\\.)*)"'
DECL = re.compile(r'\tpublic static GeneSetting (\w+) = new GeneSetting\n\t\{\n(.*?)\n\t\};', re.S)


def unescape(raw: str) -> str:
    out = []
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == '\\' and i + 1 < len(raw):
            n = raw[i + 1]
            if n == 'n':
                out.append('\n')
            elif n == 'r':
                out.append('\r')
            elif n == 't':
                out.append('\t')
            elif n in '"\\\'':
                out.append(n)
            elif n == 'u':
                out.append(chr(int(raw[i + 2:i + 6], 16)))
                i += 4
            else:
                out.append(n)
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def rust_str(text: str) -> str:
    parts = []
    for ch in text:
        if ch == '\\':
            parts.append('\\\\')
        elif ch == '"':
            parts.append('\\"')
        elif ch == '\n':
            parts.append('\\n')
        elif ch == '\r':
            parts.append('\\r')
        elif ch == '\t':
            parts.append('\\t')
        elif ord(ch) < 32 or ord(ch) > 126:
            parts.append('\\u{%x}' % ord(ch))
        else:
            parts.append(ch)
    return '"' + ''.join(parts) + '"'


settings = {}
for field, body in DECL.findall(source):
    name = re.search(r'Name = ' + STRING, body)
    help_text = re.search(r'HelperText = ' + STRING, body)
    maximum = re.search(r'maxValue = (-?[\d.]+(?:[eE][-+]?\d+)?)f?', body)
    minimum = re.search(r'minValue = (-?[\d.]+(?:[eE][-+]?\d+)?)f?', body)
    precision = re.search(r'\bprecision = (-?\d+)', body)
    units = re.search(r'\bunits = ' + STRING, body)
    prefix = re.search(r'\bprefix = ' + STRING, body)
    factor = re.search(r'\bfactor = (-?[\d.]+(?:[eE][-+]?\d+)?)f?', body)
    sign = re.search(r'\balwaysShowSign = (true|false)', body)
    si = re.search(r'\bSI = (true|false)', body)
    gene = re.search(r'gene = BibiteGenes\.Genes\.(\w+)', body)
    if not (name and gene and maximum):
        continue
    settings[field] = {
        'gene': gene.group(1),
        'name': unescape(name.group(1)),
        'help': unescape(help_text.group(1)) if help_text else '',
        'max': float(maximum.group(1)),
        'min': float(minimum.group(1)) if minimum else 0.0,
        'precision': int(precision.group(1)) if precision else 0,
        'units': unescape(units.group(1)) if units else '',
        'prefix': unescape(prefix.group(1)) if prefix else '',
        'factor': float(factor.group(1)) if factor else 1.0,
        'sign': bool(sign and sign.group(1) == 'true'),
        'si': not (si and si.group(1) == 'false'),
    }

order = re.search(r'public static List<GeneSetting> geneSettings = new List<GeneSetting>\n\t\{\n(.*?)\n\t\};', source, re.S)
fields = [f.strip() for f in order.group(1).replace('\n', ' ').split(',') if f.strip()]
missing = [f for f in fields if f not in settings]
assert not missing, f'gene settings without a declaration: {missing}'

lines = [
    '//! Generated by `tools/extract_gene_info.py` from the game\'s `BibiteEditorSettings.geneSettings`:',
    '//! the genes in the order the species panel lists them, with their `GeneSetting.Name`, help text, range and',
    '//! number format. Do not edit by hand.',
    '',
    '/// One gene of the species panel\'s Genes tab.',
    '#[derive(Clone, Copy, Debug)]',
    'pub struct GeneInfo {',
    '    /// The `BibiteGenes.Genes` member (the core\'s `GeneDef::name`).',
    '    pub gene: &\'static str,',
    '    /// `GeneSetting.Name`.',
    '    pub name: &\'static str,',
    '    /// `GeneSetting.HelperText`.',
    '    pub help: &\'static str,',
    '    /// `GeneSetting.maxValue`.',
    '    pub max: f32,',
    '    /// `GeneSetting.minValue` (the core has it too: a test checks the two tables against each other).',
    '    #[allow(dead_code)]',
    '    pub min: f32,',
    '    /// `FloatSetting.formatting`: the digits after the point,',
    '    pub precision: i32,',
    '    /// the text after the number,',
    "    pub units: &'static str,",
    '    /// the text before it,',
    "    pub prefix: &'static str,",
    '    /// the factor the value is multiplied by,',
    '    pub factor: f32,',
    '    /// whether the sign is always shown',
    '    pub always_show_sign: bool,',
    '    /// and whether it is written with SI prefixes.',
    '    pub si: bool,',
    '}',
    '',
    f'/// The genes in `geneSettings` order ({len(fields)}).',
    f'pub const GENES: [GeneInfo; {len(fields)}] = [',
]
for field in fields:
    s = settings[field]
    lines.append('    GeneInfo {')
    lines.append(f'        gene: {rust_str(s["gene"])},')
    lines.append(f'        name: {rust_str(s["name"])},')
    lines.append(f'        help: {rust_str(s["help"])},')
    lines.append(f'        max: {s["max"]!r},')
    lines.append(f'        min: {s["min"]!r},')
    lines.append(f'        precision: {s["precision"]},')
    lines.append(f'        units: {rust_str(s["units"])},')
    lines.append(f'        prefix: {rust_str(s["prefix"])},')
    lines.append(f'        factor: {s["factor"]!r},')
    lines.append(f'        always_show_sign: {"true" if s["sign"] else "false"},')
    lines.append(f'        si: {"true" if s["si"] else "false"},')
    lines.append('    },')
lines.append('];')
lines.append('')
out_path.write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(fields)} genes -> {out_path}')
