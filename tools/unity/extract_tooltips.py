"""Writes `crates/bibites-view/src/tooltip_data.rs`: every titled `TooltipTrigger` of the game's scenes.

The release build strips MonoBehaviour typetrees, so the component is read from its raw bytes: a 32-byte
header, then `title` and `content` (u32 length + UTF-8, padded to 4 bytes) and the bools `active`,
`isUITooltip` and `instant` (4 bytes each). The key is the GameObject's path from the scene root, the same
string as the `path` of the captured runtime UI nodes.

Usage: python tools/unity/extract_tooltips.py <game data dir> <output .rs>
Read-only on the game install. Needs UnityPy (the python at C:\\Users\\Storme\\.pyenv\\pyenv-win\\versions\\3.11.0).
"""
import os
import struct
import sys

import UnityPy

SCENES = ('level1', 'level2')  # the title menu and the world


def load(data_dir, scene):
    env = UnityPy.load(os.path.join(data_dir, scene))
    return env, {o.path_id: o for o in env.objects}


def script_namer(data_dir, objects):
    external = {}
    cache = {}

    def resolve(owner, file_id, path_id):
        if file_id == 0:
            return objects.get(path_id)
        entry = owner.assets_file.externals[file_id - 1]
        name = os.path.basename(entry.path)
        if name not in external:
            loaded = UnityPy.load(os.path.join(data_dir, name))
            external[name] = {o.path_id: o for o in loaded.objects}
        return external[name].get(path_id)

    def script_name(owner, raw):
        file_id, path_id = struct.unpack_from('<iq', raw, 16)
        key = (file_id, path_id)
        if key not in cache:
            try:
                target = resolve(owner, file_id, path_id)
                cache[key] = '?' if target is None else target.read().m_ClassName
            except Exception:  # noqa: BLE001
                cache[key] = '?'
        return cache[key]

    return script_name


def read_string(raw, offset):
    length = struct.unpack_from('<I', raw, offset)[0]
    text = raw[offset + 4:offset + 4 + length].decode('utf-8')
    return text, (offset + 4 + length + 3) & ~3


def game_object_path(objects, go_id):
    go = objects[go_id].read_typetree()
    transform_id = None
    for component in go['m_Component']:
        comp = objects.get(component['component']['m_PathID'])
        if comp is not None and comp.type.name in ('RectTransform', 'Transform'):
            transform_id = comp.path_id
            break
    names = [go['m_Name']]
    seen = set()
    while transform_id is not None and transform_id not in seen:
        seen.add(transform_id)
        tree = objects[transform_id].read_typetree()
        parent_id = tree['m_Father']['m_PathID']
        if parent_id == 0 or parent_id not in objects:
            break
        parent = objects[parent_id].read_typetree()
        names.append(objects[parent['m_GameObject']['m_PathID']].read_typetree()['m_Name'])
        transform_id = parent_id
    return '/'.join(reversed(names))


def tooltips_of(data_dir, scene):
    env, objects = load(data_dir, scene)
    script_name = script_namer(data_dir, objects)
    rows = []
    for obj in env.objects:
        if obj.type.name != 'MonoBehaviour':
            continue
        raw = obj.get_raw_data()
        if len(raw) < 40 or script_name(obj, raw) != 'TooltipTrigger':
            continue
        title, offset = read_string(raw, 32)
        content, offset = read_string(raw, offset)
        flags = raw[offset:offset + 12]
        if not title:
            continue  # `TooltipTrigger.Start` disables the component without a title
        go_id = struct.unpack_from('<iq', raw, 0)[1]
        rows.append({
            'path': game_object_path(objects, go_id),
            'title': title,
            'content': content,
            'ui': flags[4] != 0,
            'instant': flags[8] != 0,
        })
    return rows


def rust_string(text):
    out = ['"']
    for char in text:
        if char == '\\':
            out.append('\\\\')
        elif char == '"':
            out.append('\\"')
        elif char == '\n':
            out.append('\\n')
        elif char == '\r':
            out.append('\\r')
        elif char == '\t':
            out.append('\\t')
        elif ord(char) < 0x20:
            out.append('\\u{%x}' % ord(char))
        else:
            out.append(char)
    out.append('"')
    return ''.join(out)


def main():
    data_dir, out_path = sys.argv[1], sys.argv[2]
    rows = []
    for scene in SCENES:
        rows.extend(tooltips_of(data_dir, scene))
    # One entry per path (a few GameObjects carry two triggers: the first one wins), sorted for
    # binary search.
    by_path = {}
    for row in rows:
        by_path.setdefault(row['path'], row)
    ordered = sorted(by_path.values(), key=lambda row: row['path'])
    lines = [
        '//! Generated by `tools/unity/extract_tooltips.py` from the game\'s scenes: every titled',
        '//! `TooltipTrigger` (title, description, `isUITooltip`, `instant`) keyed by the GameObject path.',
        '//! Do not edit by hand.',
        '',
        'use crate::tooltip::Tip;',
        '',
        '/// Sorted by `path`.',
        'pub const TOOLTIPS: &[Tip] = &[',
    ]
    for row in ordered:
        lines.append('    Tip {')
        lines.append(f'        path: {rust_string(row["path"])},')
        lines.append(f'        title: {rust_string(row["title"])},')
        lines.append(f'        content: {rust_string(row["content"])},')
        lines.append(f'        ui: {"true" if row["ui"] else "false"},')
        lines.append(f'        instant: {"true" if row["instant"] else "false"},')
        lines.append('    },')
    lines.append('];')
    lines.append('')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(lines))
    print(f'{len(ordered)} tooltips written to {out_path}')


main()
