"""Generates crates/bibites-view/src/node_info_data.rs from Here/Utility.InformationWrapers/NodeInformations.cs:
the name, description, range and linearity of every input, output and node function (the neuron tooltips).
usage: python -X utf8 -I gen_node_info.py"""
import re

SRC = r'Z:/RUSTibites/Here/Utility.InformationWrapers/NodeInformations.cs'
OUT = r'Z:/RUSTibites/crates/bibites-view/src/node_info_data.rs'

text = open(SRC, encoding='utf-8').read()


def lists():
    for name in ('inputs', 'outputs', 'functions'):
        start = text.index(f'public static List<NodeInformation> {name} =')
        end = text.index('};', start)
        yield name, text[start:end]


def csharp_string(token):
    # a C# string literal: "..." with \n \t \" \\ escapes
    body = token[1:-1]
    out = []
    i = 0
    while i < len(body):
        c = body[i]
        if c == '\\':
            n = body[i + 1]
            out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\', "'": "'"}[n])
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def rust_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'


field = re.compile(r'(index|name|desc|minOutput|maxOutput|isLinear)\s*=\s*("(?:[^"\\]|\\.)*"|[^,\r\n]+?)\s*(?:,|\r?\n)', re.S)
out = []
out.append('''//! The game's descriptions of the brain's nodes (`NodeInformations`): the name, the text, the output range and
//! whether the function is linear of every input, output and activation function. Generated by
//! `tools/unity/gen_node_info.py` from the decompiled `Here/Utility.InformationWrapers/NodeInformations.cs`;
//! do not edit by hand.

/// One entry of `NodeInformations` (`NodeInformation`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct NodeInfo {
    /// `index`: the input / output number, or the `NodeType` of a function.
    pub index: usize,
    /// `name`.
    pub name: &'static str,
    /// `desc`.
    pub desc: &'static str,
    /// `isLinear`: the same input always gives the same output.
    pub is_linear: bool,
    /// `minOutput` (`-inf` when unbounded).
    pub min_output: f32,
    /// `maxOutput` (`inf` when unbounded).
    pub max_output: f32,
}
''')
for name, body in lists():
    entries = []
    for block in re.findall(r'new NodeInformation\s*\{(.*?)\}', body, re.S):
        values = {'isLinear': 'true', 'minOutput': 'float.NegativeInfinity', 'maxOutput': 'float.PositiveInfinity'}
        for key, value in field.findall(block + '\n'):
            values[key] = value.strip()
        entries.append(values)

    def num(token):
        if token == 'float.NegativeInfinity':
            return 'f32::NEG_INFINITY'
        if token == 'float.PositiveInfinity':
            return 'f32::INFINITY'
        return token.rstrip('f') + ('.0' if re.fullmatch(r'-?\d+f?', token) else '')

    out.append(f'\n/// `NodeInformations.{name}`.\npub const {name.upper()}: [NodeInfo; {len(entries)}] = [')
    for e in entries:
        out.append('    NodeInfo {')
        out.append(f'        index: {e["index"]},')
        out.append(f'        name: {rust_string(csharp_string(e["name"]))},')
        out.append(f'        desc: {rust_string(csharp_string(e["desc"]))},' if 'desc' in e else '        desc: "",')
        out.append(f'        is_linear: {e["isLinear"]},')
        out.append(f'        min_output: {num(e["minOutput"])},')
        out.append(f'        max_output: {num(e["maxOutput"])},')
        out.append('    },')
    out.append('];')
    print(name, len(entries))
out.append('''
/// `NodeInformations.InfoOfInput`.
#[must_use]
pub fn of_input(index: usize) -> Option<&'static NodeInfo> {
    INPUTS.iter().find(|info| info.index == index)
}

/// `NodeInformations.InfoOfOutPut`.
#[must_use]
pub fn of_output(index: usize) -> Option<&'static NodeInfo> {
    OUTPUTS.iter().find(|info| info.index == index)
}

/// `NodeInformations.InfoOfFunction` by the `NodeType`'s number.
#[must_use]
pub fn of_function(function: usize) -> Option<&'static NodeInfo> {
    FUNCTIONS.iter().find(|info| info.index == function)
}

/// `NodeInformations.InfoOfIndex`: the description of node `index` of a brain (inputs, outputs, then the
/// functions of the hidden nodes: `function` is the hidden node's `NodeType`).
#[must_use]
pub fn of_node(index: usize, function: usize) -> Option<&'static NodeInfo> {
    if index < INPUTS.len() {
        of_input(index)
    } else if index < INPUTS.len() + OUTPUTS.len() {
        of_output(index - INPUTS.len())
    } else {
        of_function(function)
    }
}

impl NodeInfo {
    /// `NodeInformation.rangeText`: "Output range: 0 to 1".
    #[must_use]
    pub fn range_text(&self) -> String {
        let bound = |value: f32, lowest: bool| -> String {
            let unbounded = if lowest { value <= -10_000_000.0 } else { value >= 1_000_000.0 };
            if unbounded {
                if lowest { "-Inf" } else { "Inf" }.to_owned()
            } else {
                format!("{}", value as i32)
            }
        };
        format!(
            "Output range: {} to {}",
            bound(self.min_output, true),
            bound(self.max_output, false)
        )
    }
}
''')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('written', OUT)
