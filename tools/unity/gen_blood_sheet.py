"""Writes crates/bibites-view/src/blood_sheet.rs: the `blood particles` texture of the blood `ParticleSystem` (sharedassets2.assets, 70 x 28, 10 x 4 tiles of
7 x 7 pixels), as the alpha and the brightness (the largest colour channel: the material's `_ColorMode` is Color, which keeps the particle colour's hue and
saturation and the texture's value) of each pixel, top row first.

python tools/unity/gen_blood_sheet.py "C:/Users/Storme/TheBibites/The Bibites_Data"
"""
import sys

import UnityPy

env = UnityPy.load(sys.argv[1].replace(chr(92), '/').rstrip('/') + '/sharedassets2.assets')
texture = next(o for o in env.objects if o.path_id == 57).read()
assert (texture.m_Width, texture.m_Height) == (70, 28), (texture.m_Width, texture.m_Height)
image = texture.image.convert('RGBA')
alpha, value = [], []
for y in range(28):
    for x in range(70):
        r, g, b, a = image.getpixel((x, y))
        alpha.append(a)
        value.append(max(r, g, b))


def rows(values):
    return '\n'.join('    ' + ', '.join(str(v) for v in values[i:i + 35]) + ',' for i in range(0, len(values), 35))


out = [
    '//! Generated by tools/unity/gen_blood_sheet.py from the game\'s `blood particles` texture; do not edit.',
    '',
    '/// Pixels across and down.',
    'pub const WIDTH: usize = 70;',
    'pub const HEIGHT: usize = 28;',
    '',
    '/// The alpha of each pixel, top row first.',
    'pub const ALPHA: [u8; WIDTH * HEIGHT] = [',
    rows(alpha),
    '];',
    '',
    '/// The largest colour channel of each pixel, top row first.',
    'pub const VALUE: [u8; WIDTH * HEIGHT] = [',
    rows(value),
    '];',
    '',
]
open('crates/bibites-view/src/blood_sheet.rs', 'w', encoding='utf8', newline='\n').write('\n'.join(out))
print('ok', sorted(set(alpha)), sorted(set(value))[:8])
