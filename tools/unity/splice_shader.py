"""python splice_shader.py <internals_shaders.rs> <fn name> <new generated .rs>: replace the generated function `fn name` by the translator's new output.
The doc line of the existing function (it names the shader and its asset path) is kept; the `#[allow]` attribute and the function are replaced."""
import re
import sys

path, fn_name, new_path = sys.argv[1:4]
s = open(path, encoding='utf-8').read()
new = open(new_path, encoding='utf-8').read().strip('\n')
new_lines = new.split('\n')
# drop the translator's own doc line: the file keeps the provenance line it has
assert new_lines[0].startswith('/// Generated by tools/unity/'), new_lines[0]
new_body = '\n'.join(new_lines[1:])
start_re = re.compile(r'(?m)^pub fn %s\(' % re.escape(fn_name))
m = start_re.search(s)
assert m, 'function not found: ' + fn_name
doc_start = s.rfind('/// Generated by tools/unity/', 0, m.start())
assert doc_start >= 0 and m.start() - doc_start < 600, 'header not found'
doc_end = s.index('\n', doc_start) + 1
end = s.index('\n}\n', m.start()) + 3
s = s[:doc_end] + new_body + '\n' + s[end:]
open(path, 'w', encoding='utf-8').write(s)
print('spliced', fn_name, len(new_body), 'bytes')
