"""Extracts the names and help texts of the zone, default-bibite, material and user settings (the rows of
the dynamic panel's list items and of the Settings screens) from the decompiled game source into
crates/bibites-view/src/item_help_data.rs.

Usage: python tools/extract_item_help.py [Here] [out.rs]

Sources: Here/SettingScripts/ZoneSettings.cs, BibiteSettings.cs, MatterMaterialSettings.cs, UserSettings.cs. Every
`public ... Setting field = new ... { Name = "...", HelperText = "...", ... };` that has a help text becomes
one entry (`TooltipTrigger.UpdateText(setting.Name, setting.HelperText)` is only called for those).
Run again after the game is updated; `Here/` is not part of the repository.
"""
import re
import sys
from pathlib import Path

here = Path(sys.argv[1] if len(sys.argv) > 1 else 'Here')
out_path = Path(sys.argv[2] if len(sys.argv) > 2 else 'crates/bibites-view/src/item_help_data.rs')

SOURCES = [
    ('zone', here / 'SettingScripts' / 'ZoneSettings.cs'),
    ('bibite', here / 'SettingScripts' / 'BibiteSettings.cs'),
    ('material', here / 'SettingScripts' / 'MatterMaterialSettings.cs'),
    ('user', here / 'SettingScripts' / 'UserSettings.cs'),
]

DECL = re.compile(r'^\tpublic (?:static )?(?:readonly )?[\w<>]+ (\w+) = new ')
STRING = r'"((?:[^"\\]|\\.)*)"'


def unescape(raw: str) -> str:
    out = []
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == '\\' and i + 1 < len(raw):
            n = raw[i + 1]
            if n == 'n':
                out.append('\n')
            elif n == 'r':
                out.append('\r')
            elif n == 't':
                out.append('\t')
            elif n in '"\\\'':
                out.append(n)
            elif n == 'u':
                out.append(chr(int(raw[i + 2:i + 6], 16)))
                i += 4
            else:
                out.append(n)
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def rust_str(text: str) -> str:
    parts = []
    for ch in text:
        if ch == '\\':
            parts.append('\\\\')
        elif ch == '"':
            parts.append('\\"')
        elif ch == '\n':
            parts.append('\\n')
        elif ch == '\r':
            parts.append('\\r')
        elif ch == '\t':
            parts.append('\\t')
        elif ord(ch) < 0x20:
            parts.append('\\u{%x}' % ord(ch))
        else:
            parts.append(ch)
    return '"' + ''.join(parts) + '"'


rows = []
for group, path in SOURCES:
    lines = path.read_text(encoding='utf-8').splitlines()
    index = 0
    while index < len(lines):
        match = DECL.match(lines[index])
        if not match:
            index += 1
            continue
        field = match.group(1)
        if lines[index].rstrip().endswith(';'):
            index += 1  # a one-line initializer (an event): no body
            continue
        body = []
        index += 1
        while index < len(lines) and lines[index] != '\t};':
            body.append(lines[index])
            index += 1
        text = '\n'.join(body)
        name = re.search(r'\bName = ' + STRING, text)
        helper = re.search(r'\bHelperText = ' + STRING, text)
        if name and helper and unescape(helper.group(1)).strip():
            rows.append((group, field, unescape(name.group(1)), unescape(helper.group(1))))
        index += 1

lines = [
    '//! Generated by `tools/extract_item_help.py` from the decompiled game source: the name and help text',
    "//! of every zone, default-bibite, material and user setting that has one (the tooltip of its row in the",
    "//! dynamic panel's list items and in the Settings screens). Do not edit by hand.",
    '',
    '/// One setting\'s tooltip text.',
    '#[derive(Clone, Copy, Debug)]',
    'pub struct ItemHelp {',
    '    /// `zone`, `bibite`, `material` or `user`.',
    '    pub group: &\'static str,',
    '    /// The C# field name.',
    '    pub field: &\'static str,',
    '    /// `Setting.Name` (the tooltip title).',
    '    pub name: &\'static str,',
    '    /// `Setting.HelperText` (the tooltip text).',
    '    pub help: &\'static str,',
    '}',
    '',
    'pub const ITEM_HELP: &[ItemHelp] = &[',
]
for group, field, name, helper in rows:
    lines.append('    ItemHelp {')
    lines.append(f'        group: {rust_str(group)},')
    lines.append(f'        field: {rust_str(field)},')
    lines.append(f'        name: {rust_str(name)},')
    lines.append(f'        help: {rust_str(helper)},')
    lines.append('    },')
lines.append('];')
lines.append('')
out_path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'{len(rows)} entries written to {out_path}')
